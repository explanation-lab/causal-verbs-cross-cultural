"""Build static Console entries while preserving the approved local review pilots."""
from pathlib import Path
import itertools, json, shutil, re, random

ROOT=Path(__file__).resolve().parents[1]
DEMOGRAPHICS=['age','sex','birth_country','current_country','race_ethnicity','first_language','other_languages_spoken','other_languages','everyday_language']

def replace_once(text,old,new):
    if text.count(old)!=1: raise ValueError('Expected one source marker: '+old[:70])
    return text.replace(old,new,1)

def build(name,ns,slug):
    source=ROOT/'Pilots'/name
    raw=(source/'js/materials.js').read_text()
    data=json.loads(raw[raw.index('{',raw.index('const materials =')):raw.index(';',raw.index('const materials ='))])
    variants={}
    for c in data['cases']:variants.setdefault(c['case'],[]).append(c['variant'])
    families=list(variants)
    thick_variants={}
    for f in families:
        seen=set();thick_variants[f]=[]
        for c in data['cases']:
            if c['case']!=f:continue
            signature=json.dumps([c['setup'],c['endings']['thick'],[v['text'] for k,v in c['targets'].items() if k.endswith('_thick')]])
            if signature not in seen:
                seen.add(signature);thick_variants[f].append(c['variant'])
            if name=='Absences':break
    # Weight the two participant groups by their numbers of distinct material
    # versions. Quotas within a family count identical thick wording once.
    thick_count=sum(map(len,thick_variants.values()));thin_count=sum(map(len,variants.values()))
    thick_total=round(100*thick_count/(thick_count+thin_count))
    cells={}
    for condition,pool,total in [('thick',thick_variants,thick_total),('thin',variants,100-thick_total)]:
        combos=list(itertools.product(*(range(len(v)) for v in pool.values())))
        base,remainder=divmod(total,len(combos));assert base>=1
        rng=random.Random(20261028)
        for attempt in range(100000):
            extras=set(rng.sample(combos,remainder))
            counts=[[sum(x[j]==i for x in extras) for i in range(len(pool[f]))] for j,f in enumerate(families)]
            if all(max(c)-min(c)<=1 for c in counts):break
        else:raise ValueError('Cannot balance allocation quotas')
        for indices in combos:
            code=condition if len(combos)==1 else condition+'_'+''.join(str(i) for i in indices)
            cells[code]={'verb_condition':condition,'variants':{f:pool[f][i] for f,i in zip(families,indices)},'target':base+(indices in extras)}
    assert sum(c['target'] for c in cells.values())==100
    marginals={}
    for condition in ['thick','thin']:
        assert sum(c['target'] for c in cells.values() if c['verb_condition']==condition)==(thick_total if condition=='thick' else 100-thick_total)
        pool=thick_variants if condition=='thick' else variants
        marginals[condition]={f:{v:sum(c['target'] for c in cells.values() if c['verb_condition']==condition and c['variants'][f]==v) for v in vs} for f,vs in pool.items()}
        if condition=='thin' or name!='Absences':
            assert all(max(counts.values())-min(counts.values())<=1 for counts in marginals[condition].values())
    target=source/'collection';target.mkdir(exist_ok=True)
    for folder in ['js','css','vendor']:(target/folder).mkdir(exist_ok=True)
    for filename in ['materials.js','core.js','config.js']:
        text=(source/'js'/filename).read_text()
        if filename=='config.js':text=text.replace(slug+'-english-1.0.0',slug+'-english-console-2.0.0')
        (target/'js'/filename).write_text(text)
    shutil.copyfile(source/'css/study.css',target/'css/study.css')
    for f in (ROOT/'Pilots/Absences/vendor').iterdir():
        if f.is_file():shutil.copyfile(f,target/'vendor'/f.name)
    index=(source/'index.html').read_text().replace('../Absences/vendor/','vendor/')
    (target/'index.html').write_text(index)
    allocation={'study':name,'total':100,'conditions':{'thick':thick_total,'thin':100-thick_total},'distinct_versions':{'thick':thick_count,'thin':thin_count},'cells':cells,'variant_targets':marginals,'demographic_fields':DEMOGRAPHICS}
    (target/'allocation.json').write_text(json.dumps(allocation,indent=2)+'\n')
    version=slug+'-english-console-2.0.0'
    text=(source/'js/study.js').read_text()
    declaration="/* Static Console collection entry generated by tools/build_collection.py. */\n"+f"const EXPERIMENT_VERSION = {json.dumps(version)};\nconst CONDITION_ASSIGNMENT = 'between_participant';\nconst AVAILABLE_CONDITIONS = {json.dumps(list(cells))};\nconst INTERNAL_FACTORS = ['verb_condition','case','variant','sentence_order','case_order'];\nconst CLIENT_PATH = './explanation-lab-client.js';\n"
    text=text.replace('(function() {','(async function() {',1)
    text=re.sub(r'const review=globalThis\.[A-Z_]+===true;','const review=false;',text,count=1)
    text=replace_once(text,"const storageKey='causal-verbs-"+slug+"-'+config.studyVersion;","let storageKey='causal-verbs-"+slug+"-'+config.studyVersion;\n  const allocation="+json.dumps(cells)+";\n  let explanationLab, launchCell, savePromise;\n  const studyStarted=performance.now();")
    start=text.index('  async function request(');end=text.index('  function page(',start)
    text=text[:start]+text[end:]
    text=replace_once(text,'data:{...screen,condition:selected.condition,','data:{...screen,condition:explanationLab.launch.condition,verb_condition:selected.condition,\n        trial_role:screen.stage===\'rating\'?\'response\':screen.stage===\'demographics\'?\'demographic\':screen.stage,\n        item_id:screen.case??null,measure:screen.stage===\'rating\'?\'naturalness\':screen.stage,')
    text=replace_once(text,'delete data.stimulus;','delete data.stimulus;\n        if (data.demographics) Object.assign(data,data.demographics);')
    start=text.index('  async function complete()');end=text.index('  function run(',start)
    text=text[:start]+'''  async function complete() {
    if (!state.consented) return;
    const ratings=state.records.filter(r=>r.stage==='rating');
    const expected=core.screens(selected).filter(s=>s.stage==='rating');
    if (ratings.length!==expected.length || !ratings.every((r,i)=> {
      const s=expected[i],item=core.material(materials,selected,s.case);
      return r.case===s.case && r.role===s.role && r.variant===item.variant &&
        r.sentence===item.sentences[s.sentence_position-1].text &&
        r.condition===explanationLab.launch.condition && Number.isInteger(r.rating) && r.rating>=1 && r.rating<=7;
    }) || !state.records.some(r=>r.stage==='feedback')) throw new Error('The complete assigned study is required before saving.');
    state.complete=true;persist();
    if (state.saved && explanationLab.launch.mode==='sandbox') {
      target.innerHTML=page('<h1>Thank you!</h1><p>Your responses have already been saved. You may close this window.</p>');return;
    }
    if (savePromise) return savePromise;
    target.innerHTML=page('<h1>Saving your responses…</h1><p>Please keep this page open.</p>');
    savePromise=(async()=> {
      try {
        await explanationLab.submitAndRedirect(jsPsych.data.get(), {
          durationMs:performance.now()-studyStarted,showRetryScreen:false,
          metadata:{experimentVersion:EXPERIMENT_VERSION,schemaVersion:'2.0.0',
            demographicFields:DEMOGRAPHIC_FIELDS,verb_condition:selected.condition,
            assigned_variants:selected.variants,case_order:selected.case_order,sentence_order:selected.sentence_order,
            materials_sha256:materials.source.sha256,expected_rating_count:expected.length},
        });
        state.saved=true;persist();
        if (explanationLab.launch.mode==='sandbox') target.innerHTML=page('<h1>Sandbox complete</h1><p>Responses saved to the Explanation Lab.</p>');
      } catch(error) {
        savePromise=null;
        target.innerHTML=page('<h1>Your responses have not been saved yet</h1><p>Please keep this page open and retry. You will return to Prolific only after saving succeeds.</p><button id="retry-save">Retry saving</button>');
        document.getElementById('retry-save').onclick=complete;
        console.error('Study save needs retry',error);
      }
    })();
    return savePromise;
  }
''' + text[end:]
    text=replace_once(text,'jsPsych.data.addProperties({session_id:state.id,condition:selected.condition,','jsPsych.data.addProperties({session_id:state.id,condition:explanationLab.launch.condition,verb_condition:selected.condition,')
    marker='    if(!review && state.complete) {complete();return;}'
    text=replace_once(text,marker,'    for (const record of state.records) jsPsych.data.get().push({...record});\n'+marker)
    start=text.index('  async function start()');end=text.index('    globalThis.',start)
    # The first globalThis after start belongs to the exposed review controller.
    text=text[:start]+'''  async function start() {
    const params=new URLSearchParams(location.search);
    if (!params.get('study')) throw new Error('Open this study using its Study Console link. For researcher review, use ../preview.html.');
    const {default:createExplanationLabClient}=await import(CLIENT_PATH);
    explanationLab=await createExplanationLabClient({experimentVersion:EXPERIMENT_VERSION});
    if (explanationLab.study.experimentVersion!==EXPERIMENT_VERSION ||
      explanationLab.study.conditions.length!==AVAILABLE_CONDITIONS.length ||
      AVAILABLE_CONDITIONS.some(c=>!explanationLab.study.conditions.includes(c))) throw new Error('This launch link belongs to a different study or version.');
    launchCell=allocation[explanationLab.launch.condition];
    if (!launchCell) throw new Error('Unknown Console allocation group.');
    const identity=JSON.stringify([explanationLab.launch.studyKey,explanationLab.launch.mode,
      explanationLab.launch.participant.prolificPid,explanationLab.launch.participant.studyId,
      explanationLab.launch.participant.sessionId,explanationLab.launch.condition]);
    storageKey+=':'+identity;
    try {state=JSON.parse(localStorage.getItem(storageKey));}catch{}
    if (state) {
      selected=core.validateAssignment(state.assignment);
      if (selected.condition!==launchCell.verb_condition ||
        core.CASES.some(c=>selected.variants[c]!==launchCell.variants[c])) throw new Error('Saved materials do not match the assigned version.');
    } else {
      selected=core.assignment(launchCell.verb_condition,launchCell.variants);
      state={id:crypto.randomUUID(),consented:false,records:[],next:0,complete:false,assignment:selected};
    }
    persist();
''' + text[end:]
    text=text.replace('href="preview.html"','href="../preview.html"')
    text=text.replace("console.error(error);});","console.error(error);});")
    (target/'js/study.js').write_text(declaration+'const DEMOGRAPHIC_FIELDS = '+json.dumps(DEMOGRAPHICS)+';\n'+text)
    print(name, len(cells),'allocation groups',json.dumps(marginals['thin']))

if __name__=='__main__':
    for args in [('Absences','Absence','absences'),('Factivity','Factivity','factivity'),('Chains','Chains','chains')]:build(*args)
