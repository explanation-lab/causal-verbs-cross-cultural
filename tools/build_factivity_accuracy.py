"""Build the separately registered English-learner accuracy follow-up.

Preserves all seven original cases byte-for-byte at the object level. Adds only
the approved phone/ruin and sewer/overwhelm thin materials from the workbook.
The original pilots, their collection entries, and translations are untouched.
"""
from pathlib import Path
import argparse
import copy
import hashlib
import json
import shutil
import openpyxl
from build_collection import build

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Pilots/Factivity'
DEST = ROOT / 'Pilots/FactivityAccuracy'
PROBE = 'Imagine someone is trying to learn English from you and asks you to indicate how accurate each of these statements is:'
SINGLE_PROBE = 'Imagine someone is trying to learn English from you and asks you to indicate how accurate this statement is:'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workbook', type=Path)
    args = parser.parse_args()
    original = (SOURCE / 'js/materials.js').read_text()
    materials = json.JSONDecoder().raw_decode(original[original.index('{\n'):])[0]
    assert hashlib.sha256(args.workbook.read_bytes()).hexdigest() == materials['source']['sha256'], 'Review workbook changes before rebuilding.'
    rows = list(openpyxl.load_workbook(args.workbook, read_only=True, data_only=True)['English source'].values)
    def cell(row):
        return rows[row-1][12]
    for family, base_variant, variant, ending_row, target_rows in [
        ('sewer_system', 'stop_working', 'overwhelm', 129, [133,137,139,143]),
        ('phone', 'turn_off', 'ruin', 163, [167,171,173,177]),
    ]:
        item = copy.deepcopy(next(c for c in materials['cases'] if c['case']==family and c['variant']==base_variant))
        item['variant'] = variant
        item['endings']['thin'] = cell(ending_row)
        item['source_rows']['ending_single_thin'] = ending_row
        for role, row in zip(['fact_cause','fact_lexical','direct_cause','direct_lexical'], target_rows):
            item['targets'][role+'_thin'] = {'text':cell(row), 'source_text':cell(row), 'source_row':row, 'row_key':rows[row-1][0]}
        materials['cases'].append(item)
    materials['source']['filter'] = {'Study':'fact', 'Thin-pair type':'alternating plus approved nonalternating additions'}
    materials['source']['additions'] = ['sewer_system/overwhelm', 'phone/ruin']
    for folder in ['js','css']:
        (DEST/folder).mkdir(parents=True,exist_ok=True)
    (DEST/'js/materials.js').write_text('// Generated by tools/build_factivity_accuracy.py.\n(function(root){const materials = '+json.dumps(materials,indent=2,ensure_ascii=False)+';\nif(typeof module!==\'undefined\' && module.exports) module.exports=materials; else root.FactivityMaterials=materials;\n})(globalThis);\n')
    shutil.copyfile(SOURCE/'css/study.css', DEST/'css/study.css')
    core = (SOURCE/'js/core.js').read_text()
    core = core.replace("sewer_system:['stop_working']", "sewer_system:['stop_working','overwhelm']").replace("phone:['die_kill','turn_off']", "phone:['die_kill','turn_off','ruin']")
    (DEST/'js/core.js').write_text(core)
    config = (SOURCE/'js/config.js').read_text().replace('factivity-english-1.0.0','factivity-accuracy-english-1.0.0')
    config = config.replace("  duration:", "  measure:'accuracy',\n  probeId:'english-learner-cause-and-burn',\n  scaleMin:1, scaleMax:7, scaleAnchors:['Completely inaccurate','Completely accurate'],\n  duration:")
    (DEST/'js/config.js').write_text(config)
    text = (SOURCE/'js/study.js').read_text()
    text = text.replace("'causal-verbs-factivity-'", "'causal-verbs-factivity-accuracy-'").replace('`factivity-${','`factivity-accuracy-${')
    text = text.replace('/api/factivity/', '/api/factivity-accuracy/')
    text = text.replace('naturalness', 'accuracy').replace('Naturalness rating','Accuracy rating').replace('Very unnatural','Completely inaccurate').replace('Very natural','Completely accurate')
    text = text.replace('How natural is this sentence as a description of the situation?', SINGLE_PROBE)
    text = text.replace('Please carefully read all of the following sentences before rating them.', PROBE+' Please carefully read all four statements before rating them.')
    text = text.replace('For each story, you\'ll read four sentences about what happened, and then you\'ll rate each sentence.', 'For each story, you\'ll read four sentences about what happened, and then you\'ll rate the accuracy of each sentence. '+PROBE+' Use the scale from 1 (Completely inaccurate) to 7 (Completely accurate).')
    text = text.replace('study_version:config.studyVersion});', 'study_version:config.studyVersion,probe_id:config.probeId,rating_scale_min:config.scaleMin,rating_scale_max:config.scaleMax,rating_scale_anchors:config.scaleAnchors});')
    (DEST/'js/study.js').write_text(text)
    review = (SOURCE/'js/review.js').read_text().replace("['phone','scooter']", "['sewer_system','phone','scooter']")
    (DEST/'js/review.js').write_text(review)
    preview = (SOURCE/'preview.html').read_text().replace('Factivity — researcher review','Factivity accuracy — researcher review')
    preview = preview.replace('<option value="thin">Thin alternating verbs</option>', '<option value="thin">Thin verbs</option>')
    preview = preview.replace('<label>Phone story', '<label>Sewer story <select id="review-sewer_system"><option value="stop_working">Stop working</option><option value="overwhelm">Overwhelm</option></select></label>\n        <label>Phone story')
    preview = preview.replace('<option value="turn_off">Texting / manufacturing defect</option>', '<option value="turn_off">Texting / turn off</option><option value="ruin">Texting / ruin</option>')
    preview = preview.replace('<a href="../Factivity/preview.html" aria-current="page">Factivity</a>', '<a href="../Factivity/preview.html">Original Factivity</a><a href="preview.html" aria-current="page">Factivity accuracy</a>')
    preview = preview.replace('<h1>Factivity pilot</h1>','<h1>Factivity accuracy pilot</h1>').replace('the naturalness ratings. Inspect both conditions and all seven source versions.', 'the English-learner accuracy ratings. Inspect both conditions and all nine thin versions, including phone/ruin and sewer/overwhelm.')
    (DEST/'preview.html').write_text(preview)
    index = (SOURCE/'index.html').read_text().replace('<title>Factivity', '<title>Factivity accuracy')
    (DEST/'index.html').write_text(index)
    build('FactivityAccuracy','Factivity','factivity-accuracy',measure='accuracy')


if __name__ == '__main__':
    main()
